@Suppress("CyclomaticComplexMethod", "unused")
internal fun checkListed(event: AnalyticsEvent): Unit = when (event) {
    is AnalyticsEvent.ScreenView, is AnalyticsEvent.MushafPage, is AnalyticsEvent.ReadingEnd,
    is AnalyticsEvent.HizbOpen, is AnalyticsEvent.HizbFinish, is AnalyticsEvent.HizbNext,
    is AnalyticsEvent.AudioPlay, is AnalyticsEvent.AudioDownload, is AnalyticsEvent.AudioError,
    is AnalyticsEvent.DoorOpen, is AnalyticsEvent.StationOpen, is AnalyticsEvent.JourneyFinish,
    is AnalyticsEvent.Search, is AnalyticsEvent.SearchOpenResult, is AnalyticsEvent.SearchOptionsOpen,
    is AnalyticsEvent.SearchZero, is AnalyticsEvent.SaveAdd, is AnalyticsEvent.SaveRemove,
    is AnalyticsEvent.CollectionCreate, is AnalyticsEvent.CollectionShare, is AnalyticsEvent.NoteAdd,
    is AnalyticsEvent.ComposeStart, is AnalyticsEvent.ComposeSubmit, is AnalyticsEvent.ComposeCancel,
    is AnalyticsEvent.LiveOpenTiktok, is AnalyticsEvent.VideoPlay, is AnalyticsEvent.RemindToggle,
    is AnalyticsEvent.NotificationOpen, is AnalyticsEvent.NotificationSetting, is AnalyticsEvent.ThemeSet,
    is AnalyticsEvent.LocationSourceSet, is AnalyticsEvent.ReminderSet, is AnalyticsEvent.UpdateSeen,
    is AnalyticsEvent.UpdateOpen, is AnalyticsEvent.ContentMismatch, is AnalyticsEvent.StudyOpen,
    is AnalyticsEvent.StudyFollow, is AnalyticsEvent.TabOpen, is AnalyticsEvent.DhikrCardOpen,
    is AnalyticsEvent.AyahSheetOpen, is AnalyticsEvent.AyahActionTap, is AnalyticsEvent.MediaControl,
    is AnalyticsEvent.PlayerOptionSet, is AnalyticsEvent.WidgetOpen, is AnalyticsEvent.SpellingFormOpen,
    is AnalyticsEvent.ModeratorMessageSend, is AnalyticsEvent.SignInPrompt, is AnalyticsEvent.SignInResultEvent,
    is AnalyticsEvent.TaskTime, is AnalyticsEvent.EaseAnswer,
    -> Unit
}
